const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const C=require('../atlas-core.js');
require('./import-gedcom.cjs').selfTest();
assert.equal(C.fold('ŻÓŁĆ Łąka'),'zolc laka');
assert.equal(C.located({lat:null,lon:null}),false);
assert.equal(C.located({lat:0,lon:0}),true);
assert.equal(C.located({lat:91,lon:10}),false);
const raw={people:[{id:'p',givenName:'Ewa',surname:'Żak'},{id:'child',givenName:'Jan'}],families:[{id:'f',wifeId:'p',children:['child']}],events:[{id:'e',people:['p'],type:'birth',year:1800,date:'około 1800',place:'Ruda',lat:50,lon:21},{id:'u',people:['p'],type:'death',place:'Ruda'},{id:'x',people:['p'],type:'marriage',date:{raw:'AFT 1850',kind:'after',year:1850}}]};
const d=C.normalize(raw),s={query:'zak',unknown:true,from:null,to:null};
assert.equal(d.events.filter(e=>C.matches(e,s,d)).length,3);
assert.equal(C.matches(d.events[1],{...s,unknown:false},d),false);
assert.equal(C.matches(d.events[2],{...s,from:1900},d),true);
assert.equal(C.matches(d.events[0],{...s,from:1900},d),false);
assert.deepEqual(C.relatives('p',d).children,['child']);
assert.deepEqual(C.relatives('child',d).parents,['p']);
assert.equal(C.matches(d.events[0],{...s,from:2000,to:1800},d),false);
assert.equal(C.escape('<img src=x onerror="evil()">'),'&lt;img src=x onerror=&quot;evil()&quot;&gt;');
const root=path.resolve(__dirname,'..'),approved=JSON.parse(fs.readFileSync(path.join(root,'data/genealogia.json'),'utf8'));
const context={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'data/atlas-data.js'),'utf8'),context);
assert.equal(JSON.stringify(context.window.ATLAS_DATA),JSON.stringify(approved),'Publiczny pakiet musi być dokładnie kopią zatwierdzonego JSON-a');
